import fs from 'node:fs';
import assert from 'node:assert/strict';
const rmd=fs.readFileSync(new URL('../cuentas.Rmd',import.meta.url),'utf8');
const js=fs.readFileSync(new URL('../js/accounts-v1.js',import.meta.url),'utf8');
const schema=fs.readFileSync(new URL('../js/schema.js',import.meta.url),'utf8');
const picker=fs.readFileSync(new URL('../js/date-picker.js',import.meta.url),'utf8');
const debts=fs.readFileSync(new URL('../js/debts.js',import.meta.url),'utf8');
const reconciliation=fs.readFileSync(new URL('../js/reconciliation.js',import.meta.url),'utf8');
assert.match(rmd,/<dialog id="account-editor"/,'la cuenta debe crearse/editarse en ventana modal');
assert.match(rmd,/data-account-type="savings"/,'tipo de cuenta debe estar arriba como selector visual');
assert.match(rmd,/id="opening-balance" type="text" inputmode="decimal"/,'saldo inicial debe usar teclado decimal');
assert.match(rmd,/id="last4" type="text" inputmode="numeric"/,'últimos 4 debe usar teclado numérico');
assert.match(rmd,/id="opening-balance-as-of" type="date"/,'fecha base debe usar sistema global de calendario');
assert.match(rmd,/id="account-detail"/,'debe existir detalle por icono de información');
assert.match(js,/tf-account-list-table/,'la vista principal debe ser listado/tabla');
assert.match(js,/data-info=/,'el listado debe abrir detalle mediante icono de información');
assert.match(js,/saveAccount\(data,editingId\)/,'editar debe conservar el mismo document ID');
assert.doesNotMatch(rmd,/MIG-/,'Cuentas no debe mostrar bloques de migración');
assert.match(schema,/Los últimos 4 dígitos deben contener solo números/,'la capa canónica debe validar last4');
assert.match(picker,/showPicker/,'las fechas deben abrir calendario sin edición textual');
assert.match(debts,/searchParams|URLSearchParams/,'Deudas/tarjetas debe aceptar navegación desde una cuenta');
assert.match(debts,/get\("card"\)/,'el enlace Planes debe preseleccionar/resaltar la tarjeta solicitada');
assert.match(reconciliation,/get\("account"\)/,'Conciliación debe preseleccionar la cuenta solicitada desde Cuentas');
const {sanitizeAccountWrite}=await import('../js/schema.js');
const validCard={bank:'Banco',alias:'Tarjeta',accountType:'credit_card',last4:'1234',openingBalance:-10,openingBalanceAsOf:'2026-11-14',closingDay:18,paymentDay:5,reminderDaysBefore:3,creditLimit:1000,statementBalance:0,minimumPayment:0};
assert.equal(sanitizeAccountWrite(validCard).last4,'1234');
assert.throws(()=>sanitizeAccountWrite({...validCard,last4:'12A4'}),/solo números/,'last4 alfanumérico debe rechazarse en capa canónica');
assert.throws(()=>sanitizeAccountWrite({...validCard,closingDay:99}),/día de corte/,'no se debe recortar silenciosamente el día de corte');

console.log('accounts-ui-v1082: OK');
